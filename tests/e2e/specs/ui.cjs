const SHOTS = process.env.E2E_SHOTS || require('path').join(__dirname, '..', 'shots');
require('fs').mkdirSync(SHOTS, { recursive: true });
const B_ENV = process.env.E2E_BASE || 'http://127.0.0.1:4400';
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 360, height: 740 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type()==='error' && !/401/.test(m.text()) && errs.push(m.text()));
  await p.goto(B_ENV + '/');
  await p.getByRole('button', { name: 'Login', exact: true }).click();
  const name = p.getByLabel(/^Subcont/);
  const autoc = await name.evaluate(el => [el.getAttribute('autocapitalize'), el.getAttribute('autocorrect'), el.getAttribute('spellcheck')]);
  console.log('atribut input:', autoc.join(','));
  await name.fill('CV UJI SATU'); await p.locator('input[name=password]').fill('salah');
  await p.getByRole('button', { name: 'Masuk', exact: true }).click();
  await p.getByRole('alert').filter({ hasText: 'salah' }).waitFor();
  console.log('pesan gagal:', await p.locator('form [role=alert]').first().innerText());
  await p.waitForTimeout(300); await p.screenshot({ path: require('path').join(SHOTS, 't2-login-gagal.png') });
  await name.fill('  cv uji   satu'); await p.locator('input[name=password]').fill('Daya4385');
  await p.getByRole('button', { name: 'Masuk', exact: true }).click();
  await p.getByRole('heading', { name: /^Halo,/ }).waitFor();
  console.log('beranda:', (await p.locator('h1').innerText()), '|', await p.getByText('CV UJI SATU').first().innerText());
  await p.waitForTimeout(400); await p.screenshot({ path: require('path').join(SHOTS, 't2-beranda-login.png') });
  await p.reload(); await p.getByRole('heading', { name: /^Halo,/ }).waitFor(); console.log('sesi dipulihkan setelah reload: ya');
  const cookies = await p.context().cookies(); console.log('cookie httpOnly:', cookies.find(c=>c.name==='whc_session')?.httpOnly);
  console.log('document.cookie terlihat JS:', JSON.stringify(await p.evaluate(() => document.cookie)));
  await p.getByRole('button', { name: 'Keluar', exact: true }).click();
  await p.getByRole('button', { name: 'Login', exact: true }).waitFor(); console.log('keluar: ya');
  await p.reload(); await p.getByRole('button', { name: 'Login', exact: true }).waitFor(); console.log('setelah keluar + reload tetap logout: ya');
  console.log(errs.length ? 'ERR ' + errs.join(' | ') : 'tanpa error JS');
  await b.close();
})();
